export const generateRecentHabitCompletions = (): HabitCompletion[] => {
  const completions: HabitCompletion[] = [];
  const today = new Date();
  
  // Generate completions for past 21 days for realistic streaks
  for (let d = 0; d < 21; d++) {
    const targetDate = new Date();
    targetDate.setDate(today.getDate() - d);
    const dateStr = targetDate.toISOString().split('T')[0];
    const isToday = d === 0;

    // Habit 1: completed almost every day
    completions.push({
      id: `hc-1-${d}`,
      habitId: 'habit-1',
      userId: 'usr_demo_01',
      date: dateStr,
      completed: isToday ? true : d % 7 !== 4, // 1 skip 4 days ago
      count: 1,
    });

    // Habit 2: completed on weekdays
    const dayOfWeek = targetDate.getDay();
    const isWeekday = dayOfWeek >= 1 && dayOfWeek <= 5;
    if (isWeekday) {
      completions.push({
        id: `hc-2-${d}`,
        habitId: 'habit-2',
        userId: 'usr_demo_01',
        date: dateStr,
        completed: isToday ? false : true,
        count: isToday ? 0 : 1,
      });
    }

    // Habit 3: completed evening
    completions.push({
      id: `hc-3-${d}`,
      habitId: 'habit-3',
      userId: 'usr_demo_01',
      date: dateStr,
      completed: isToday ? false : true,
      count: isToday ? 0 : 1,
    });

    // Habit 4: reading
    completions.push({
      id: `hc-4-${d}`,
      habitId: 'habit-4',
      userId: 'usr_demo_01',
      date: dateStr,
      completed: isToday ? true : d !== 8,
      count: 1,
    });
  }

  return completions;
};

